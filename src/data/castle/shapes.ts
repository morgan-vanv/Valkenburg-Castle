// Region shapes for the castle layout, ported 1:1 from mockup/sketch.py so the
// game matches the approved sketch hex for hex. Shapes are predicates on
// "odd-r" offset (col, row), the same grid as offsetToAxial in src/game/hex.ts.

export type Shape = (c: number, r: number) => boolean;

/** Sketch world space: one column ~ 1 hex wide, one row ~ 0.866 tall. */
function toWorld(c: number, r: number): [number, number] {
  return [c + 0.5 * (r & 1), r * 0.866];
}

