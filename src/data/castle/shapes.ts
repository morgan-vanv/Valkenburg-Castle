/** An ellipse around (cx, cy) with radii in hexes; `jitter` bumps the rim in 12 sectors. */
export function ellipse(cx: number, cy: number, rx: number, ry: number, jitter = 0, seed = 0): Shape {
  let bumps: number[] = new Array<number>(12).fill(0);
  if (jitter) {
    const draws = PY_RANDOM[seed];
    if (!draws) throw new Error(`shapes: no random table for seed ${seed}`);
    bumps = draws.map((u) => -jitter + (jitter - -jitter) * u);
  }
  const [X, Y] = toWorld(cx, cy);
  return (c, r) => {
    const [x, y] = toWorld(c, r);
    const dx = (x - X) / rx;
    const dy = (y - Y) / (ry * 0.866);
    const a = Math.atan2(dy, dx);
    const k = bumps[Math.floor(((a + Math.PI) / (2 * Math.PI)) * 12) % 12]!;
    return dx * dx + dy * dy <= (1 + k) ** 2;
  };
}

export function rect(c0: number, r0: number, c1: number, r1: number): Shape {
  return (c, r) => c0 <= c && c <= c1 && r0 <= r && r <= r1;
}

/** Hexes near a polyline through (col, row) points. */
export function line(points: [number, number][], width = 0): Shape {
  const segs = points.slice(1).map((b, i) => [points[i]!, b] as const);
  return (c, r) => {
    const [x, y] = toWorld(c, r);
    for (const [a, b] of segs) {
      const [ax, ay] = toWorld(a[0], a[1]);
      const [bx, by] = toWorld(b[0], b[1]);
      const vx = bx - ax;
      const vy = by - ay;
      const L = vx * vx + vy * vy || 1;
      const t = Math.max(0, Math.min(1, ((x - ax) * vx + (y - ay) * vy) / L));
      const px = ax + t * vx;
      const py = ay + t * vy;
      if ((x - px) ** 2 + (y - py) ** 2 <= (0.55 + width) ** 2) return true;
    }
    return false;
  };
}

export function union(...fs: Shape[]): Shape {
  return (c, r) => fs.some((f) => f(c, r));
}

export function minus(f: Shape, g: Shape): Shape {
  return (c, r) => f(c, r) && !g(c, r);
}

/** The single hex (c, r). */
export function cell(c: number, r: number): Shape {
  return (cc, rr) => cc === c && rr === r;
}
